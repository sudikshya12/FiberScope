export function ErrorState({ error, onRetry }: { error: unknown; onRetry?: () => void }) {
  const msg = error instanceof Error ? error.message : 'Something went wrong.'
  return (
    <div role="alert" className="flex items-start gap-3 rounded-xl border border-[#ecc5ca] bg-crit-soft/60 p-4 text-sm">
      <XCircle className="mt-0.5 size-5 shrink-0 text-crit" aria-hidden />
      <div className="min-w-0 flex-1">
        <div className="font-semibold text-crit">Request failed</div>
        <div className="mt-0.5 break-words text-ink/80">{msg}</div>
      </div>
      {onRetry && (
        <Button size="sm" onClick={onRetry}>
          Retry
        </Button>
      )}
    </div>
  )
}

export function InlineError({ error }: { error: unknown }) {
  if (!error) return null
  const msg = error instanceof Error ? error.message : String(error)
  return (
    <motion.div initial={{ opacity: 0, y: -4 }} animate={{ opacity: 1, y: 0 }} role="alert" className="mt-2 flex items-start gap-2 rounded-lg border border-[#ecc5ca] bg-crit-soft px-3 py-2 text-[13px] text-crit">
      <AlertTriangle className="mt-0.5 size-3.5 shrink-0" aria-hidden />
      <span className="min-w-0 break-words">{msg}</span>
    </motion.div>
  )
}

// ---------------------------------------------------------------- Tabs

export function Tabs({ value, onValueChange, items, className, listClass, children }: { value: string; onValueChange: (v: string) => void; items: { value: string; label: ReactNode; count?: number }[]; className?: string; listClass?: string; children: ReactNode }) {
  return (
    <RTabs.Root value={value} onValueChange={onValueChange} className={clsx('flex min-h-0 flex-col', className)}>
      <RTabs.List className={clsx('relative flex shrink-0 gap-1 border-b border-line-2 px-2', listClass)}>
        {items.map((it) => (
          <RTabs.Trigger
            key={it.value}
            value={it.value}
            className="relative flex items-center gap-1.5 px-2.5 py-2.5 text-[13px] font-medium text-muted outline-none transition-colors hover:text-ink focus-visible:rounded-md focus-visible:ring-2 focus-visible:ring-accent/40 data-[state=active]:text-ink"
          >
            {it.label}
            {it.count != null && <span className="rounded bg-canvas px-1 font-mono text-[10.5px] text-muted">{it.count}</span>}
            {value === it.value && <motion.span layoutId={`tab-${items.map((i) => i.value).join('')}`} className="absolute inset-x-1.5 -bottom-px h-0.5 rounded-full bg-accent" transition={{ type: 'spring', stiffness: 500, damping: 38 }} />}
          </RTabs.Trigger>
        ))}
      </RTabs.List>
      {children}
    </RTabs.Root>
  )
}
