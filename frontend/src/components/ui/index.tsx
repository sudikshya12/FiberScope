// ---------------------------------------------------------------- Copy & raw output

export function CopyButton({ text, label = 'Copy' }: { text: string; label?: string }) {
  const [done, setDone] = useState(false)
  return (
    <button
      type="button"
      onClick={async () => {
        try {
          await navigator.clipboard.writeText(text)
          setDone(true)
          setTimeout(() => setDone(false), 1400)
        } catch {
          /* clipboard unavailable */
        }
      }}
      className="inline-flex items-center gap-1 rounded-md px-1.5 py-1 text-[11px] font-medium text-faint transition-colors hover:bg-white/10 hover:text-white"
      aria-label={label}
    >
      {done ? <Check className="size-3" aria-hidden /> : <Copy className="size-3" aria-hidden />}
      {done ? 'Copied' : label}
    </button>
  )
}

export function RawOutput({ text, title = 'Raw output', simulated = true, maxH = 'max-h-72' }: { text: string; title?: string; simulated?: boolean; maxH?: string }) {
  return (
    <div className="overflow-hidden rounded-lg border border-[#2c2a31] bg-[#1d1c21]">
      <div className="flex items-center justify-between border-b border-white/[0.06] px-3 py-1.5">
        <span className="font-mono text-[10.5px] uppercase tracking-wider text-[#a29eab]">
          {title}
          {simulated && <span className="ml-2 rounded bg-white/10 px-1 text-[#d8d5de]">simulated</span>}
        </span>
        <CopyButton text={text} />
      </div>
      <pre className={clsx('scroll-thin overflow-auto px-3 py-2.5 text-[11.5px] leading-[1.55] text-[#e4e1e8]', maxH)}>{text}</pre>
    </div>
  )
}

export function Segmented<T extends string>({ value, onChange, options, label }: { value: T; onChange: (v: T) => void; options: { value: T; label: ReactNode }[]; label: string }) {
  return (
    <div role="radiogroup" aria-label={label} className="relative inline-flex rounded-lg border border-line bg-canvas p-0.5">
      {options.map((o) => (
        <button
          key={o.value}
          role="radio"
          aria-checked={value === o.value}
          onClick={() => onChange(o.value)}
          className={clsx('relative z-10 rounded-md px-2.5 py-1 text-[12.5px] font-medium transition-colors', value === o.value ? 'text-ink' : 'text-muted hover:text-ink')}
        >
          {value === o.value && <motion.span layoutId={`seg-${label}`} className="absolute inset-0 -z-10 rounded-md border border-line bg-white shadow-[var(--shadow-panel)]" transition={{ type: 'spring', stiffness: 500, damping: 38 }} />}
          {o.label}
        </button>
      ))}
    </div>
  )
}

