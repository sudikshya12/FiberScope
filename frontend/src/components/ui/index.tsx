// ---------------------------------------------------------------- Dialog

export function Dialog({ open, onOpenChange, title, description, children, wide }: { open: boolean; onOpenChange: (o: boolean) => void; title: string; description?: string; children: ReactNode; wide?: boolean }) {
  return (
    <RDialog.Root open={open} onOpenChange={onOpenChange}>
      <AnimatePresence>
        {open && (
          <RDialog.Portal forceMount>
            <RDialog.Overlay asChild>
              <motion.div className="fixed inset-0 z-50 bg-[#1c1b20]/35 backdrop-blur-[2px]" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} />
            </RDialog.Overlay>
            <RDialog.Content asChild>
              <motion.div
                className={clsx('fixed left-1/2 top-1/2 z-50 max-h-[88vh] w-[calc(100vw-2rem)] overflow-y-auto rounded-xl border border-line bg-white p-5 shadow-[var(--shadow-pop)] scroll-thin', wide ? 'max-w-3xl' : 'max-w-lg')}
                initial={{ opacity: 0, scale: 0.96, x: '-50%', y: '-48%' }}
                animate={{ opacity: 1, scale: 1, x: '-50%', y: '-50%' }}
                exit={{ opacity: 0, scale: 0.97, x: '-50%', y: '-48%' }}
                transition={{ type: 'spring', stiffness: 420, damping: 32 }}
              >
                <div className="mb-4 flex items-start justify-between gap-4">
                  <div>
                    <RDialog.Title className="text-lg font-semibold text-ink">{title}</RDialog.Title>
                    {description ? <RDialog.Description className="mt-1 text-sm text-muted">{description}</RDialog.Description> : <RDialog.Description className="sr-only">{title}</RDialog.Description>}
                  </div>
                  <RDialog.Close asChild>
                    <button className="rounded-lg p-1.5 text-muted hover:bg-canvas hover:text-ink" aria-label="Close dialog">
                      <X className="size-4" />
                    </button>
                  </RDialog.Close>
                </div>
                {children}
              </motion.div>
            </RDialog.Content>
          </RDialog.Portal>
        )}
      </AnimatePresence>
    </RDialog.Root>
  )
}

