// ---------------------------------------------------------------- Button

type Variant = 'primary' | 'secondary' | 'ghost' | 'danger' | 'subtle'
type Size = 'sm' | 'md' | 'lg'

export const Button = forwardRef<HTMLButtonElement, ButtonHTMLAttributes<HTMLButtonElement> & { variant?: Variant; size?: Size; loading?: boolean; icon?: ReactNode }>(
  function Button({ variant = 'secondary', size = 'md', loading, icon, className, children, disabled, ...rest }, ref) {
    return (
      <button
        ref={ref}
        disabled={disabled || loading}
        className={clsx(
          'group relative inline-flex select-none items-center justify-center gap-2 whitespace-nowrap rounded-lg font-medium transition-all duration-150 active:scale-[0.98] disabled:cursor-not-allowed disabled:opacity-50 disabled:active:scale-100',
          size === 'sm' && 'h-8 px-2.5 text-[13px]',
          size === 'md' && 'h-9 px-3.5 text-sm',
          size === 'lg' && 'h-11 px-5 text-[15px]',
          variant === 'primary' && 'bg-accent text-white hover:bg-accent-strong',
          variant === 'secondary' && 'border border-line bg-white text-ink hover:border-[#cfc9d6] hover:bg-[#fbfafc]',
          variant === 'ghost' && 'text-muted hover:bg-black/[0.04] hover:text-ink',
          variant === 'subtle' && 'bg-accent-soft text-accent-strong hover:bg-[#e6dcf7]',
          variant === 'danger' && 'border border-[#ecc5ca] bg-white text-crit hover:bg-crit-soft',
          className,
        )}
        {...rest}
      >
        {loading ? <Loader2 className="size-4 animate-spin" aria-hidden /> : icon}
        {children}
      </button>
    )
  },
)

// ---------------------------------------------------------------- Badges

export function Badge({ children, tone = 'neutral', className, title }: { children: ReactNode; tone?: 'neutral' | 'accent' | 'ok' | 'warn' | 'crit' | 'dark' | 'outline'; className?: string; title?: string }) {
  return (
    <span
      title={title}
      className={clsx(
        'inline-flex items-center gap-1 whitespace-nowrap rounded-md px-1.5 py-0.5 text-[11px] font-semibold leading-4 tracking-wide',
        tone === 'neutral' && 'bg-unknown-soft text-[#4f4c57]',
        tone === 'accent' && 'bg-accent-soft text-accent-strong',
        tone === 'ok' && 'bg-ok-soft text-ok',
        tone === 'warn' && 'bg-warn-soft text-warn',
        tone === 'crit' && 'bg-crit-soft text-crit',
        tone === 'dark' && 'bg-nav text-white',
        tone === 'outline' && 'border border-line bg-white text-muted',
        className,
      )}
    >
      {children}
    </span>
  )
}

